"""Safety checks for the ACI DNS helper; no Azure account or real keys are used."""

import contextlib
import copy
import importlib.util
import io
import json
import os
from pathlib import Path
import stat
import subprocess
import unittest
from unittest import mock


SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "azure-set-dns.py"
SPEC = importlib.util.spec_from_file_location("azure_set_dns", SCRIPT)
helper = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(helper)

SUBSCRIPTION = "00000000-1111-2222-3333-444444444444"
GROUP = "portfolio-demo-group"
NAME = "playwright-action-api"
LABEL = "portfolio-browser-demo"
SYNTHETIC_PASSWORD = "synthetic-registry-password-never-a-real-key"
RESOURCE_ID = (
    f"/subscriptions/{SUBSCRIPTION}/resourceGroups/{GROUP}/providers/"
    f"Microsoft.ContainerInstance/containerGroups/{NAME}"
)


def exported_group():
    return {
        "apiVersion": "2021-10-01",
        "type": "Microsoft.ContainerInstance/containerGroups",
        "id": RESOURCE_ID,
        "etag": "read-only-resource-metadata",
        "name": NAME,
        "location": "eastus",
        "tags": {"purpose": "portfolio", "owner": "example"},
        "properties": {
            "osType": "Linux",
            "restartPolicy": "OnFailure",
            "provisioningState": "Succeeded",
            "containers": [{
                "name": NAME,
                "properties": {
                    "image": "demoacr.azurecr.io/playwright-action-api:showcase",
                    "resources": {"requests": {"cpu": 4, "memoryInGB": 16}},
                    "ports": [{"port": 3000, "protocol": "TCP"}],
                    "environmentVariables": [{"name": "PORT", "value": "3000"}],
                    "volumeMounts": [{"name": "scratch", "mountPath": "/scratch"}],
                    "instanceView": {"restartCount": 2},
                },
            }],
            "ipAddress": {
                "type": "Public",
                "ip": "192.0.2.5",
                "ports": [{"port": 3000, "protocol": "TCP"}],
                "autoGeneratedDomainNameLabelScope": "ResourceGroupReuse",
            },
            "imageRegistryCredentials": [{"server": "demoacr.azurecr.io", "username": "demoacr"}],
            "volumes": [{"name": "scratch", "emptyDir": {}}],
        },
    }


class AzureSetDnsTests(unittest.TestCase):
    def setUp(self):
        self.original_umask = os.umask(0o077)
        self.addCleanup(os.umask, self.original_umask)
        self.document = exported_group()
        self.latest_document = None
        self.calls = []
        self.export_paths = []
        self.export_modes = []
        self.created_payload = None
        self.payload_path = None
        self.payload_mode = None
        self.directory_mode = None
        self.admin_enabled = True
        self.admin_username = "demoacr"
        self.fail_create = False
        self.resource_id = RESOURCE_ID
        self.output = io.StringIO()
        self.real_az = helper.az
        self.hidden_password = mock.Mock(return_value=SYNTHETIC_PASSWORD)

    def fake_az(self, *args):
        self.calls.append(args)
        command = args[:2]
        if command == ("account", "show"):
            return json.dumps(SUBSCRIPTION)
        if command == ("container", "export"):
            target = Path(args[args.index("--file") + 1])
            document = self.document
            if self.export_paths and self.latest_document is not None:
                document = self.latest_document
            target.write_text(helper.yaml.safe_dump(document))
            self.export_paths.append(target)
            self.export_modes.append(stat.S_IMODE(target.stat().st_mode))
            return ""
        if command == ("container", "show"):
            query = args[args.index("--query") + 1]
            return json.dumps(self.resource_id if query == "id" else {
                "fqdn": f"{LABEL}.eastus.azurecontainer.io", "state": "Succeeded"
            })
        if command == ("acr", "show"):
            return json.dumps(self.admin_enabled)
        if args[:3] == ("acr", "credential", "show"):
            return json.dumps({
                "username": self.admin_username,
                "passwords": [{"name": "password", "value": SYNTHETIC_PASSWORD}],
            })
        if command == ("container", "create"):
            self.payload_path = Path(args[args.index("--file") + 1])
            self.payload_mode = stat.S_IMODE(self.payload_path.stat().st_mode)
            self.directory_mode = stat.S_IMODE(self.payload_path.parent.stat().st_mode)
            self.created_payload = json.loads(self.payload_path.read_text())
            if self.fail_create:
                # Exercise the real subprocess wrapper's redaction rather than
                # inventing a safe exception in the mock Azure dispatcher.
                failure = subprocess.CompletedProcess(
                    ["az"], 1, stdout=SYNTHETIC_PASSWORD, stderr=SYNTHETIC_PASSWORD
                )
                with mock.patch.object(helper.subprocess, "run", return_value=failure):
                    return self.real_az(*args)
            return ""
        self.fail(f"Unexpected Azure operation in test: {args[:3]}")

    def run_helper(self, *extra):
        argv = ["--resource-group", GROUP, "--name", NAME, "--dns-name-label", LABEL, *extra]
        with mock.patch.object(helper, "az", side_effect=self.fake_az), \
                mock.patch.object(helper, "hidden_password", self.hidden_password), \
                contextlib.redirect_stdout(self.output), contextlib.redirect_stderr(self.output):
            helper.main(argv)

    def assert_no_create(self):
        self.assertFalse(any(call[:2] == ("container", "create") for call in self.calls))

    def assert_no_registry_reads(self):
        self.assertFalse(any(call[0] == "acr" for call in self.calls))
        self.hidden_password.assert_not_called()

    def assert_resource_calls_use_active_subscription(self):
        for call in self.calls:
            if call[:2] == ("account", "show"):
                continue
            self.assertIn("--subscription", call)
            self.assertEqual(call[call.index("--subscription") + 1], SUBSCRIPTION)

    def assert_private_files_removed(self):
        for target in self.export_paths:
            self.assertFalse(target.exists())
            self.assertFalse(target.parent.exists())
        if self.payload_path:
            self.assertFalse(self.payload_path.exists())

    def test_dry_run_reads_only_resource_and_never_recovers_credentials(self):
        self.run_helper("--use-existing-acr-admin")
        self.assert_no_create()
        self.assert_no_registry_reads()
        self.assertEqual(len(self.export_paths), 1)
        self.assertIn("Read-only preview complete", self.output.getvalue())
        self.assertNotIn(SYNTHETIC_PASSWORD, self.output.getvalue())
        self.assert_resource_calls_use_active_subscription()
        self.assert_private_files_removed()

    def test_apply_preserves_complete_configuration_and_privately_recovers_password(self):
        self.run_helper("--apply")
        payload = self.created_payload
        props = payload["properties"]
        container = props["containers"][0]["properties"]
        self.assertEqual(container["resources"]["requests"], {"cpu": 4, "memoryInGB": 16})
        self.assertEqual(props["restartPolicy"], "OnFailure")
        self.assertEqual(container["image"], self.document["properties"]["containers"][0]["properties"]["image"])
        self.assertEqual(container["ports"], [{"port": 3000, "protocol": "TCP"}])
        self.assertEqual(props["ipAddress"]["ports"], [{"port": 3000, "protocol": "TCP"}])
        self.assertEqual(props["ipAddress"]["autoGeneratedDomainNameLabelScope"], "ResourceGroupReuse")
        self.assertEqual(props["ipAddress"]["dnsNameLabel"], LABEL)
        self.assertEqual(payload["tags"], self.document["tags"])
        self.assertEqual(props["volumes"], self.document["properties"]["volumes"])
        self.assertEqual(container["volumeMounts"], [{"name": "scratch", "mountPath": "/scratch"}])
        self.assertEqual(container["environmentVariables"], [{"name": "PORT", "value": "3000"}])
        self.assertNotIn("ip", props["ipAddress"])
        self.assertNotIn("instanceView", container)
        self.assertNotIn("id", payload)
        self.assertEqual(props["imageRegistryCredentials"][0]["password"], SYNTHETIC_PASSWORD)
        self.hidden_password.assert_called_once_with()
        self.assertEqual(self.export_modes, [0o600, 0o600])
        self.assertEqual(self.payload_mode, 0o600)
        self.assertEqual(self.directory_mode, 0o700)
        self.assertNotIn(SYNTHETIC_PASSWORD, self.output.getvalue())
        self.assertIn("DNS hostname:", self.output.getvalue())
        self.assert_resource_calls_use_active_subscription()
        self.assert_private_files_removed()

    def test_existing_admin_credentials_are_captured_without_printing_or_changing_them(self):
        self.run_helper("--apply", "--use-existing-acr-admin")
        self.hidden_password.assert_not_called()
        self.assertIn(("acr", "show"), [call[:2] for call in self.calls])
        self.assertIn(("acr", "credential", "show"), [call[:3] for call in self.calls])
        self.assertFalse(any(call[:2] in (("acr", "update"), ("acr", "login")) for call in self.calls))
        self.assertEqual(self.created_payload["properties"]["imageRegistryCredentials"][0]["password"], SYNTHETIC_PASSWORD)
        self.assertNotIn(SYNTHETIC_PASSWORD, self.output.getvalue())
        self.assert_resource_calls_use_active_subscription()
        self.assert_private_files_removed()

    def test_disabled_admin_access_and_mismatched_user_abort_before_create(self):
        for enabled, username, message in [(False, "demoacr", "not already enabled"), (True, "other-user", "not the ACR admin")]:
            with self.subTest(enabled=enabled, username=username):
                self.calls.clear()
                self.admin_enabled = enabled
                self.admin_username = username
                with self.assertRaisesRegex(helper.SafeError, message):
                    self.run_helper("--apply", "--use-existing-acr-admin")
                self.assert_no_create()
                self.hidden_password.assert_not_called()
                if not enabled:
                    self.assertFalse(any(call[:3] == ("acr", "credential", "show") for call in self.calls))
                self.assert_private_files_removed()

    def test_exports_with_missing_settings_or_nonexportable_secrets_abort_before_credentials(self):
        cases = []
        memory = exported_group()
        del memory["properties"]["containers"][0]["properties"]["resources"]["requests"]["memoryInGB"]
        cases.append(("missing memory", memory))
        for environment in ([{"name": "API_TOKEN", "secureValue": SYNTHETIC_PASSWORD}], [{"name": "API_TOKEN"}]):
            document = exported_group()
            document["properties"]["containers"][0]["properties"]["environmentVariables"] = environment
            cases.append(("secure or omitted environment", document))
        for volume in ({"name": "private", "secret": {"file": "synthetic-base64"}}, {"name": "share", "azureFile": {"storageAccountKey": SYNTHETIC_PASSWORD}}):
            document = exported_group()
            document["properties"]["volumes"] = [volume]
            cases.append(("secret or Azure File volume", document))
        for key, value in (("diagnostics", {"logAnalytics": {"workspaceKey": SYNTHETIC_PASSWORD}}), ("extensions", [{"name": "private-extension"}])):
            document = exported_group()
            document["properties"][key] = value
            cases.append((key, document))
        for label, document in cases:
            with self.subTest(case=label):
                self.calls.clear()
                self.document = document
                with self.assertRaises(helper.SafeError) as error:
                    self.run_helper("--apply", "--use-existing-acr-admin")
                self.assertNotIn(SYNTHETIC_PASSWORD, str(error.exception))
                self.assert_no_create()
                self.assert_no_registry_reads()
                self.assert_private_files_removed()

    def test_configuration_drift_aborts_without_submitting_any_update(self):
        self.latest_document = copy.deepcopy(self.document)
        self.latest_document["properties"]["containers"][0]["properties"]["resources"]["requests"]["memoryInGB"] = 8
        with self.assertRaisesRegex(helper.SafeError, "settings changed"):
            self.run_helper("--apply")
        self.assertEqual(len(self.export_paths), 2)
        self.assert_no_create()
        self.assert_private_files_removed()

    def test_create_failure_is_generic_and_always_removes_private_payload(self):
        self.fail_create = True
        with self.assertRaises(helper.SafeError) as error:
            self.run_helper("--apply")
        self.assertIn("Azure CLI reported a failure", str(error.exception))
        self.assertNotIn(SYNTHETIC_PASSWORD, str(error.exception))
        self.assertNotIn(SYNTHETIC_PASSWORD, self.output.getvalue())
        self.assertIsNotNone(self.created_payload)
        self.assertFalse(any(call[:2] == ("container", "delete") for call in self.calls))
        self.assert_private_files_removed()

    def test_an_existing_different_dns_label_is_not_replaced(self):
        self.document["properties"]["ipAddress"]["dnsNameLabel"] = "already-public-name"
        with self.assertRaisesRegex(helper.SafeError, "different DNS label"):
            self.run_helper("--apply")
        self.assert_no_create()
        self.assert_no_registry_reads()
        self.assert_private_files_removed()

    def test_the_requested_existing_dns_label_does_not_redeploy_or_read_credentials(self):
        self.document["properties"]["ipAddress"]["dnsNameLabel"] = LABEL
        self.run_helper("--apply", "--use-existing-acr-admin")
        self.assert_no_create()
        self.assert_no_registry_reads()
        self.assertIn("DNS hostname:", self.output.getvalue())
        self.assertEqual(len(self.export_paths), 1)
        self.assert_private_files_removed()

    def test_private_acr_image_without_exported_authentication_is_not_recreated(self):
        self.document["properties"]["imageRegistryCredentials"] = []
        with self.assertRaises(helper.SafeError):
            self.run_helper("--apply")
        self.assert_no_create()
        self.assert_no_registry_reads()
        self.assert_private_files_removed()

    def test_resource_identity_mismatch_aborts_before_export_or_registry_access(self):
        self.resource_id = RESOURCE_ID.replace(GROUP, "other-resource-group")
        with self.assertRaisesRegex(helper.SafeError, "did not match"):
            self.run_helper("--apply")
        self.assertEqual(self.export_paths, [])
        self.assert_no_create()
        self.assert_no_registry_reads()


if __name__ == "__main__":
    unittest.main()
